class DummySleepStageModel(SleepStageModel):
    """Majority-class baseline."""

    def __init__(self, label_column: str = "reference_stage", seed: int = 42):
        super().__init__(label_column=label_column, seed=seed)
        self.model_name = "dummy"
        self.feature_columns: list[str] = []

    def fit(self, frame: pd.DataFrame) -> DummySleepStageModel:
        self.feature_columns = resolve_feature_group(frame, "all")
        X = frame[self.feature_columns].copy()
        y = frame[self.label_column].astype(str)
        X = X.fillna(X.median(numeric_only=True))
        self.model = Pipeline([
            ("imputer", SimpleImputer(strategy="median")),
            ("classifier", DummyClassifier(strategy="most_frequent")),
        ])
        self.model.fit(X, y)
        return self

    def predict(self, frame: pd.DataFrame) -> np.ndarray:
        X = frame[self.feature_columns].fillna(
            frame[self.feature_columns].median(numeric_only=True)
        )
        return self.model.predict(X)

    def predict_proba(self, frame: pd.DataFrame) -> np.ndarray:
        X = frame[self.feature_columns].fillna(
            frame[self.feature_columns].median(numeric_only=True)
        )
        return self.model.predict_proba(X)


