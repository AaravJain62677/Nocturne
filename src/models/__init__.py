def load_preprocessed_artifact(path: str | Path) -> pd.DataFrame:
    """Load the epoch-level parquet or csv artifact generated by preprocessing."""
    artifact_path = Path(path).expanduser().resolve()
    if not artifact_path.exists():
        raise FileNotFoundError(f"Preprocessed artifact not found: {artifact_path}")
    if artifact_path.suffix.lower() == ".parquet":
        return pd.read_parquet(artifact_path)
    return pd.read_csv(artifact_path)


def _eligible_epochs(frame: pd.DataFrame) -> pd.DataFrame:
    """Filter to non-excluded rows with a valid stage label."""
    if "reference_stage" not in frame.columns:
        raise KeyError("Artifact is missing the reference_stage label column.")
    mask = frame["reference_stage"].notna()
    if "excluded" in frame.columns:
        mask &= ~frame["excluded"].fillna(False).astype(bool)
    return frame.loc[mask].copy()


def resolve_feature_group(frame: pd.DataFrame, group_name: str) -> list[str]:
    """Resolve a feature group from the actual preprocessing schema."""
    normalized = str(group_name).strip().lower().replace(" ", "")
    available_columns = [col for col in frame.columns if str(col).startswith("feature_")]
    available = sorted(available_columns)
    if not available:
        raise ValueError("Artifact does not contain any feature columns.")

    group_map: dict[str, tuple[str, ...]] = {
        "hr": tuple(col for col in available if col.startswith("feature_hr_")),
        "hrv": tuple(col for col in available if col.startswith("feature_hrv_")),
        "accel": tuple(
            col
            for col in available
            if col.startswith("feature_accel_") or col == "feature_movement_intensity"
        ),
        "eda": tuple(col for col in available if col.startswith("feature_eda_")),
        "all": tuple(available),
        "all_wearable": tuple(available),
    }
    for key, value in {
        "hr+accel": ("hr", "accel"),
        "hr+hrv": ("hr", "hrv"),
        "hr+hrv+accel": ("hr", "hrv", "accel"),
        "hr+hrv+accel+eda": ("hr", "hrv", "accel", "eda"),
        "hr+eda": ("hr", "eda"),
        "hrrv": ("hr", "hrv"),
    }.items():
        group_map[key] = tuple(
            item for prefix in value for item in group_map.get(prefix, ())
        )

    if normalized not in group_map:
        choices = ", ".join(sorted(group_map))
        raise ValueError(f"Unsupported feature group '{group_name}'. Available groups: {choices}.")

    required_prefixes: dict[str, tuple[str, ...]] = {
        "hr": ("hr",),
        "hrv": ("hrv",),
        "accel": ("accel",),
        "eda": ("eda",),
        "hr+accel": ("hr", "accel"),
        "hr+hrv": ("hr", "hrv"),
        "hr+hrv+accel": ("hr", "hrv", "accel"),
        "hr+hrv+accel+eda": ("hr", "hrv", "accel", "eda"),
        "hr+eda": ("hr", "eda"),
        "hrrv": ("hr", "hrv"),
    }
    required = required_prefixes.get(normalized, ())
    missing = []
    for prefix in required:
        prefix_match = f"feature_{prefix}_"
        movement_ok = "feature_movement_intensity" in available
        if not any(
            col.startswith(prefix_match) or (col == "feature_movement_intensity" and movement_ok)
            for col in available
        ):
            missing.append(prefix)
    if missing:
        joined = ", ".join(missing)
        raise ValueError(
            f"Feature group '{group_name}' requires unavailable modality columns for {joined}. "
            f"Available wearable features: {available}"
        )

    selected = list(dict.fromkeys(group_map[normalized]))
    if not selected:
        raise ValueError(
            f"Feature group '{group_name}' resolves to no columns in the loaded artifact. "
            f"Available wearable features: {available}"
        )
    return selected


def build_subject_splits(
    frame: pd.DataFrame,
    seed: int = 42,
    train_ratio: float = 0.7,
    val_ratio: float = 0.15,
    test_ratio: float = 0.15,
    label_column: str = "reference_stage",
) -> dict[str, list[str]]:
    """Build subject-independent train/validation/test partitions.

    This uses the eligible subject IDs only and preserves all epochs for each subject
    within a partition. It does not silently fall back to epoch-level random splitting.
    """
    eligible = _eligible_epochs(frame)
    if label_column not in eligible.columns:
        raise KeyError(f"Label column '{label_column}' not found in feature artifact.")

    subject_ids = sorted({str(value) for value in eligible["subject_id"].dropna()})
    if not subject_ids:
        raise ValueError("No eligible subjects are available for splitting.")

    rng = np.random.default_rng(seed)
    shuffled = rng.permutation(subject_ids).tolist()
    count = len(shuffled)

    if count == 1:
        train_count = 1
        val_count = 0
        test_count = 0
    elif count == 2:
        train_count = 1
        val_count = 1
        test_count = 0
    elif count >= 3:
        # Keep every split populated whenever there are at least three subjects.
        # This preserves subject-disjoint training/validation/testing while
        # avoiding a silent empty test partition in small synthetic fixtures.
        train_count = max(1, count - 2)
        val_count = 1
        test_count = max(1, count - train_count - val_count)
        if train_count + val_count + test_count != count:
            # Rebalance deterministically when the ratio-based default would be
            # too sparse for the remaining subjects.
            test_count = count - train_count - val_count
            if test_count < 1:
                test_count = 1
                val_count = count - train_count - test_count
        if val_count < 1:
            val_count = 1
        if test_count < 1:
            test_count = 1
        if train_count + val_count + test_count > count:
            surplus = train_count + val_count + test_count - count
            train_count = max(1, train_count - surplus)
    else:
        target_train = int(round(count * train_ratio))
        target_val = int(round(count * val_ratio))
        target_test = count - target_train - target_val
        if target_train < 1:
            target_train = 1
        if target_val < 1 and count >= 3:
            target_val = 1
        if target_test < 1 and count >= 3:
            target_test = max(1, count - target_train - target_val)
        if target_train + target_val + target_test != count:
            target_test = count - target_train - target_val
        train_count = max(1, target_train)
        val_count = max(0, target_val)
        test_count = max(0, count - train_count - val_count)
        if train_count + val_count + test_count != count:
            test_count = count - train_count - val_count

    train_subjects = shuffled[:train_count]
    val_start = train_count
    val_subjects = shuffled[val_start : val_start + val_count]
    test_subjects = shuffled[val_start + val_count : val_start + val_count + test_count]

    return {
        "train": sorted(train_subjects),
        "val": sorted(val_subjects),
        "test": sorted(test_subjects),
    }


def save_split_assignments(
    split_map: dict[str, list[str]],
    output_dir: str | Path,
    prefix: str = "subject_split",
) -> dict[str, Path]:
    """Persist split assignments to disk for reproducible model runs."""
    output_path = Path(output_dir).expanduser().resolve()
    output_path.mkdir(parents=True, exist_ok=True)
    assignments_path = output_path / f"{prefix}_assignments.json"
    rows = []
    for split_name, subject_ids in split_map.items():
        for subject_id in sorted(subject_ids):
            rows.append({"subject_id": subject_id, "split": split_name})
    assignments_path.write_text(json.dumps(rows, indent=2, sort_keys=True), encoding="utf-8")

    csv_path = output_path / f"{prefix}_assignments.csv"
    pd.DataFrame(rows).to_csv(csv_path, index=False)
    return {"assignments": assignments_path, "csv": csv_path}


def compute_partition_summary(
    frame: pd.DataFrame,
    split_map: dict[str, list[str]],
    label_column: str = "reference_stage",
) -> dict[str, dict[str, Any]]:
    """Summarize subjects, recordings, epochs, and class counts per partition."""
    eligible = _eligible_epochs(frame)
    summary: dict[str, dict[str, Any]] = {}
    for split_name, subjects in split_map.items():
        subject_values = {str(subject) for subject in subjects}
        partition = eligible[eligible["subject_id"].astype(str).isin(subject_values)].copy()
        summary[split_name] = {
            "subjects": int(partition["subject_id"].nunique()),
            "recordings": int(partition["recording_id"].nunique()),
            "epochs": int(len(partition)),
            "class_counts": {
                str(label): int(count)
                for label, count in partition[label_column].value_counts().to_dict().items()
            },
        }
    return summary


def prepare_sequence_batches(
    frame: pd.DataFrame,
    sequence_length: int = 2,
    label_column: str = "reference_stage",
    subject_column: str = "subject_id",
    recording_column: str = "recording_id",
    time_column: str = "epoch_start",
    feature_columns: list[str] | None = None,
) -> list[dict[str, Any]]:
    """Create contiguous subject/recording-safe sequences without crossing boundaries."""
    if sequence_length <= 0:
        raise ValueError("sequence_length must be positive.")
    eligible = _eligible_epochs(frame).copy()
    batches: list[dict[str, Any]] = []
    for (subject_id, recording_id), group in eligible.groupby(
        [subject_column, recording_column], sort=True
    ):
        ordered = group.sort_values(time_column).copy()
        for start in range(0, len(ordered), sequence_length):
            chunk = ordered.iloc[start : start + sequence_length]
            if chunk.empty:
                continue
            if feature_columns is not None:
                feature_subset = [
                    column for column in feature_columns if column in chunk.columns
                ]
                chunk_features = chunk.loc[:, feature_subset].copy()
                if chunk_features.empty:
                    raise ValueError(
                        "The requested feature columns are not present in the "
                        "sequence data."
                    )
                feature_matrix = chunk_features.to_numpy(dtype=float)
            else:
                feature_matrix = chunk.filter(
                    regex=r"^feature_", axis=1
                ).to_numpy(dtype=float)
            labels = chunk[label_column].tolist()
            batches.append(
                {
                    "subject_ids": [str(subject_id)] * len(chunk),
                    "recording_ids": [str(recording_id)] * len(chunk),
                    "features": feature_matrix,
                    "labels": labels,
                }
            )
    return batches


class SleepStageModel:
    """Abstract base model contract for training and prediction."""

    def __init__(self, label_column: str = "reference_stage", seed: int = 42):
        self.label_column = label_column
        self.seed = seed
        self.model_name = "base"
        self.model = None

    def fit(self, frame: pd.DataFrame) -> SleepStageModel:
        raise NotImplementedError("Subclass must implement fit().")

    def predict(self, frame: pd.DataFrame) -> np.ndarray:
        if self.model is None:
            raise ValueError("Model has not been fit yet.")
        return self.model.predict(frame)

    def save_checkpoint(self, path: str | Path) -> dict[str, Any]:
        payload = {
            "model_name": self.model_name,
            "label_column": self.label_column,
            "seed": self.seed,
            "feature_columns": getattr(self, "feature_columns", []),
        }
        target = Path(path).expanduser().resolve()
        target.parent.mkdir(parents=True, exist_ok=True)
        if self.model is not None and hasattr(self.model, "__getstate__"):
            pickle_path = target.with_suffix(".pkl")
            with pickle_path.open("wb") as fh:
                pickle.dump(self.model, fh)
            payload["pickle_path"] = str(pickle_path)
        target.write_text(json.dumps(payload, indent=2, sort_keys=True), encoding="utf-8")
        return payload

    @classmethod
    def load_checkpoint(cls, path: str | Path) -> SleepStageModel:
        target = Path(path).expanduser().resolve()
        if not target.exists():
            raise FileNotFoundError(f"Checkpoint not found: {target}")
        payload = json.loads(target.read_text(encoding="utf-8"))
        model = cls(
            label_column=payload.get("label_column", "reference_stage"),
            seed=int(payload.get("seed", 42)),
        )
        model.feature_columns = payload.get("feature_columns", [])
        pickle_path = Path(payload.get("pickle_path", ""))
        if pickle_path.exists():
            with pickle_path.open("rb") as fh:
                model.model = pickle.load(fh)
        return model


