class SequenceModelSpec:
    """Training configuration for the sequence-model interface."""

    def __init__(
        self,
        sequence_length: int = 8,
        hidden_dim: int = 32,
        num_layers: int = 1,
        dropout: float = 0.1,
        learning_rate: float = 1e-3,
        patience: int = 3,
        epochs: int = 5,
    ):
        self.sequence_length = sequence_length
        self.hidden_dim = hidden_dim
        self.num_layers = num_layers
        self.dropout = dropout
        self.learning_rate = learning_rate
        self.patience = patience
        self.epochs = epochs


class _SequenceEncoder(nn.Module if nn is not None else object):
    def __init__(
        self,
        input_dim: int,
        hidden_dim: int,
        num_layers: int,
        dropout: float,
        model_type: str,
        num_classes: int = 5,
    ):
        super().__init__()
        if nn is None:
            raise ImportError("PyTorch is required for sequence models.")
        if model_type == "gru":
            self.rnn = nn.GRU(
                input_size=input_dim,
                hidden_size=hidden_dim,
                num_layers=num_layers,
                batch_first=True,
                dropout=dropout if num_layers > 1 else 0.0,
            )
        else:
            self.rnn = nn.LSTM(
                input_size=input_dim,
                hidden_size=hidden_dim,
                num_layers=num_layers,
                batch_first=True,
                dropout=dropout if num_layers > 1 else 0.0,
            )
        self.classifier = nn.Linear(hidden_dim, num_classes)

    def forward(self, features: torch.Tensor) -> torch.Tensor:
        out, _ = self.rnn(features)
        return self.classifier(out[:, -1, :])


class GRUSleepStageModel(SleepStageModel):
    """Causal GRU sequence model trained on contiguous subject/recording-safe batches."""

    def __init__(
        self,
        label_column: str = "reference_stage",
        feature_columns: list[str] | None = None,
        seed: int = 42,
        hidden_dim: int = 32,
        num_layers: int = 1,
        dropout: float = 0.1,
        sequence_length: int = 8,
        learning_rate: float = 1e-3,
        epochs: int = 2,
        patience: int = 2,
        validation_fraction: float = 0.2,
    ):
        super().__init__(label_column=label_column, seed=seed)
        self.model_name = "gru"
        self.feature_columns = feature_columns or []
        self.spec = SequenceModelSpec(
            sequence_length=sequence_length,
            hidden_dim=hidden_dim,
            num_layers=num_layers,
            dropout=dropout,
            learning_rate=learning_rate,
            patience=patience,
            epochs=epochs,
        )
        self.validation_fraction = validation_fraction
        self.training_history: list[dict[str, float]] = []
        self.model = None
        self.label_to_index: dict[str, int] = {}
        self.index_to_label: dict[int, str] = {}

    def fit(self, frame: pd.DataFrame) -> GRUSleepStageModel:
        if not self.feature_columns:
            self.feature_columns = resolve_feature_group(frame, "all")
        if nn is None:
            raise ImportError("PyTorch is required to train GRU/LSTM models.")
        sequences = prepare_sequence_batches(
            frame,
            sequence_length=self.spec.sequence_length,
            feature_columns=self.feature_columns,
        )
        if not sequences:
            raise ValueError("No valid sequences were available for training.")

        labels = sorted({str(value) for batch in sequences for value in batch["labels"]})
        self.label_to_index = {label: idx for idx, label in enumerate(labels)}
        self.index_to_label = {idx: label for label, idx in self.label_to_index.items()}

        rng = np.random.default_rng(self.seed)
        indices = rng.permutation(len(sequences))
        val_count = max(
                1,
                int(round(len(sequences) * self.validation_fraction)),
            ) if len(sequences) > 1 else 0
        val_indices = set(indices[:val_count].tolist())
        train_batches = [
            sequences[idx] for idx in range(len(sequences)) if idx not in val_indices
        ]
        val_batches = [
            sequences[idx] for idx in range(len(sequences)) if idx in val_indices
        ]
        if not train_batches:
            train_batches = sequences
            val_batches = []

        input_dim = len(self.feature_columns)
        num_classes = len(self.label_to_index)
        self.model = _SequenceEncoder(
            input_dim=input_dim,
            hidden_dim=self.spec.hidden_dim,
            num_layers=self.spec.num_layers,
            dropout=self.spec.dropout,
            model_type="gru",
            num_classes=num_classes,
        )

        criterion = nn.CrossEntropyLoss()
        optimizer = torch.optim.Adam(self.model.parameters(), lr=self.spec.learning_rate)
        best_state = None
        best_val_loss = float("inf")
        patience_count = 0

        for epoch in range(self.spec.epochs):
            self.model.train()
            train_running = 0.0
            train_examples = 0
            for batch in train_batches:
                features = torch.as_tensor(
                    np.asarray(batch["features"], dtype=np.float32),
                    dtype=torch.float32,
                )
                target_label = str(batch["labels"][-1])
                target = torch.as_tensor(
                    [self.label_to_index[target_label]],
                    dtype=torch.long,
                )
                if features.ndim == 2:
                    features = features.unsqueeze(0)
                logits = self.model(features)
                loss = criterion(logits, target)
                optimizer.zero_grad()
