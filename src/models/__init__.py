def train_model(
    frame: pd.DataFrame,
    model_name: str,
    feature_group: str = "all",
    label_column: str = "reference_stage",
    seed: int = 42,
    **kwargs,
) -> SleepStageModel:
    """Construct and fit a supported model implementation."""
    available = {
        "dummy": DummySleepStageModel,
        "random_forest": RandomForestSleepStageModel,
        "hist_gradient_boosting": HistGradientSleepStageModel,
        "gru": GRUSleepStageModel,
        "lstm": LSTMSleepStageModel,
    }
    if model_name not in available:
        raise ValueError(f"Unsupported model '{model_name}'.")

    feature_columns = resolve_feature_group(frame, feature_group)
    if model_name == "dummy":
        model = DummySleepStageModel(label_column=label_column, seed=seed)
    elif model_name == "random_forest":
        model = RandomForestSleepStageModel(
            label_column=label_column,
            feature_columns=feature_columns,
            seed=seed,
            **kwargs,
        )
    elif model_name == "hist_gradient_boosting":
        model = HistGradientSleepStageModel(
            label_column=label_column,
            feature_columns=feature_columns,
            seed=seed,
            **kwargs,
        )
    elif model_name == "gru":
        model = GRUSleepStageModel(
            label_column=label_column,
            feature_columns=feature_columns,
            seed=seed,
            **kwargs,
        )
    else:
        model = LSTMSleepStageModel(
            label_column=label_column,
            feature_columns=feature_columns,
            seed=seed,
            **kwargs,
        )
    model.fit(frame)
    return model


